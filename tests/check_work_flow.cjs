// Prepare the fictional input with: python tools/build_nontechnical_trial.py
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert/strict');
const root=path.resolve(__dirname,'..');
const data=JSON.parse(fs.readFileSync(path.join(root,'private/nontechnical-trial.json'),'utf8'));
const sheet=fs.readFileSync(path.join(root,'skills/career-context-sheet/assets/sheet.html'),'utf8');
const sections=fs.readFileSync(path.join(root,'skills/career-context-sheet/assets/sections.js'),'utf8');
const contextText=sheet.match(/function contextText\(data\)[^\n]+/)[0];
const selectedPacket=sheet.match(/function selectedPacket\(\)[^\n]+/)[0];
const functionBody=name=>sections.match(new RegExp('function '+name+'\\([^]*?\\n}'))[0];
const sandbox={packet:data,accountScope:{value:'visible'},includeSources:{checked:false},visibleAccountIds:new Set(['display-sketch'])};
vm.createContext(sandbox);
vm.runInContext(contextText+'\n'+functionBody('appendCompanionText')+'\n'+functionBody('practicePrompt')+'\n'+functionBody('preparationPrompt')+'\n'+selectedPacket,sandbox);
const scoped=sandbox.selectedPacket();
assert.deepEqual(Array.from(scoped.accounts.map(a=>a.id)),['display-sketch']);
assert.equal(scoped.person.overview,'');
for(const key of ['presentation','timeline','interview','journey','publicProfile'])assert(!(key in scoped));
const text=sandbox.preparationPrompt(data,'display-sketch');
assert(text.includes('Account ID: display-sketch'));
assert(text.includes('display remained a sketch'));
assert(text.includes('Another volunteer found boards'));
assert(!text.includes('Account ID: watering-rota'));
assert(!text.includes(data.person.overview));
assert.equal(sandbox.preparationPrompt(data,'missing'),'');
const prepared=sandbox.practicePrompt(data,'watering-rota');
assert(prepared.includes('A neighbour agreed the final rota'));
assert(!prepared.includes('Account ID: chair-repair'));
assert(!prepared.includes(data.person.overview));
sandbox.includeSources.checked=true;
assert.deepEqual(Array.from(sandbox.selectedPacket().sources.map(s=>s.id)),['display-note']);
sandbox.visibleAccountIds=new Set();
assert.equal(sandbox.selectedPacket().accounts.length,0);
sandbox.accountScope.value='all';
assert.equal(sandbox.selectedPacket().accounts.length,4);
assert.equal(sandbox.selectedPacket().sources.length,4);
console.log('Nontechnical copy scope, preparation, shared credit, unfinished work and explicit all-account export passed.');
