const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert/strict');
const root=path.resolve(__dirname,'..'),data=JSON.parse(fs.readFileSync(path.join(root,'examples/complete-context.json'),'utf8'));
const sandbox={};vm.createContext(sandbox);vm.runInContext(fs.readFileSync(path.join(root,'skills/career-context-sheet/assets/explore.js'),'utf8'),sandbox);
const first=data.timeline[0],last=data.timeline.at(-1),selection={fromId:first.id,toId:last.id,purpose:'patterns',contextSha256:'a'.repeat(64),updatedAt:1};
const range=sandbox.selectedTimelineContext(data,selection.fromId,selection.toId);
assert.equal(range.periods.length,data.timeline.length);
assert.equal(new Set(range.sources.map(s=>s.id)).size,range.sources.length);
assert.equal(sandbox.selectedTimelineContext(data,'missing',last.id).periods.length,0);
assert.equal(sandbox.selectedTimelineContext(data,last.id,first.id).periods.length,data.timeline.length);
const single=sandbox.selectedTimelineContext(data,first.id,first.id);
assert.equal(single.periods.length,1);
assert.deepEqual(Array.from(single.sources.map(s=>s.id)).sort(),[...new Set(first.sourceRefs)].sort());
const without=sandbox.timelineBrief(data,selection),withSources=sandbox.timelineBrief(data,selection,true);
assert(without.includes('Synthetic demo data'));
assert(without.includes('broader background, not proof'));
assert(without.includes('Do not infer inactivity'));
assert(without.includes('Source references follow without excerpts'));
for(const s of range.sources)assert(withSources.includes(s.content));
assert(sandbox.timelineBrief(data,{...selection,purpose:'cv'}).includes('CV bullets'));
assert(sandbox.timelineBrief(data,{...selection,purpose:'interview'}).includes('interview stories'));
assert(sandbox.timelineBrief(data,{...selection,purpose:'profile'}).includes('confidential identifiers'));
assert(sandbox.validTimelineSelection(selection,data,'a'.repeat(64)));
assert(!sandbox.validTimelineSelection({...selection,updatedAt:Infinity},data,'a'.repeat(64)));
assert(!sandbox.validTimelineSelection(selection,data,'b'.repeat(64)));
assert(!sandbox.validTimelineSelection({...selection,fromId:'missing'},data,'a'.repeat(64)));
assert(!sandbox.validTimelineSelection({...selection,purpose:'invent'},data,'a'.repeat(64)));
console.log('Timeline scope, brief boundaries and selection validation passed.');
const extra=data.accounts.find(a=>!first.accountIds.includes(a.id));
data.presentation.timelineReading={contextSha256:selection.contextSha256,periods:{[first.id]:{title:'Short',bullets:['A limit.'],accountIds:[extra.id]}},years:{}};
const enhanced=sandbox.selectedTimelineContext(data,first.id,first.id,selection.contextSha256);
assert(enhanced.accounts.some(a=>a.id===extra.id));
assert.deepEqual(Array.from(enhanced.sources.map(s=>s.id)).sort(),[...new Set(first.sourceRefs)].sort());
assert(sandbox.timelineBrief(data,{...selection,toId:first.id}).includes('BROADER ACCOUNT '+extra.id));
assert(!sandbox.selectedTimelineContext(data,first.id,first.id,'b'.repeat(64)).accounts.some(a=>a.id===extra.id));
const yearLabels=['2023','2026','2024','Other periods'].map(year=>({dataset:{year}}));
assert.equal(sandbox.latestTimelineYear(yearLabels).dataset.year,'2026');
console.log('Reviewed links, source boundaries, stale fallback and recent-year default passed.');
